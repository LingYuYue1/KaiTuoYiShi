import { describe, expect, it } from 'vitest';
import { 创建默认记忆系统设置, 归一化记忆系统设置 } from '@/models/settings';
import type { 记忆系统设置 } from '@/models/settings';

const 当前默认 = 创建默认记忆系统设置();

/** 契约版本是持久化格式版本：改动它需要配套迁移，因此钉住具体值而非只断言存在。 */
const 期望契约版本 = 2;

function 三层(input: 记忆系统设置) {
  return [input.即时转短期阈值, input.短期转中期阈值, input.中期转长期阈值];
}

describe('记忆阈值契约', () => {
  it.each([
    [25, 20, 10], // v1 早期
    [15, 15, 15], // v1.2.x
    [10, 30, 50], // 阶段1
    [15, 25, 45], // F5
  ])('无戳旧存档的历史默认组合 %s/%s/%s 抬到当前默认', (即时, 短期, 中期) => {
    const 结果 = 归一化记忆系统设置({
      即时转短期阈值: 即时,
      短期转中期阈值: 短期,
      中期转长期阈值: 中期,
    });

    expect(三层(结果)).toEqual(三层(当前默认));
  });

  it('玩家自定义过的阈值一律保留', () => {
    const 结果 = 归一化记忆系统设置({
      即时转短期阈值: 7,
      短期转中期阈值: 13,
      中期转长期阈值: 29,
      NPC记忆压缩阈值: 22,
    });

    expect(三层(结果)).toEqual([7, 13, 29]);
    expect(结果.NPC记忆压缩阈值).toBe(22);
  });

  it('已打戳存档的显式阈值不再被嗅探覆盖', () => {
    const 结果 = 归一化记忆系统设置({
      记忆阈值契约版本: 期望契约版本,
      即时转短期阈值: 25,
      短期转中期阈值: 20,
      中期转长期阈值: 10,
    });

    expect(三层(结果)).toEqual([25, 20, 10]);
  });

  it('旧 NPC 默认抬到当前默认', () => {
    expect(归一化记忆系统设置({ NPC记忆压缩阈值: 15 }).NPC记忆压缩阈值)
      .toBe(当前默认.NPC记忆压缩阈值);
  });

  it.each([
    { 名称: '阈值全为 0', 输入: { 即时转短期阈值: 0, 短期转中期阈值: 0, 中期转长期阈值: 0 } },
    { 名称: '阈值类型错误', 输入: { 即时转短期阈值: 'x', 短期转中期阈值: null, 中期转长期阈值: undefined } },
    { 名称: '嵌套配置是垃圾', 输入: { 记忆总结API: 42, 忆庭启用: 'yes', 忆庭召回提示词: 7 } },
  ])('$名称 归一化后仍是合法可用配置', ({ 输入 }) => {
    const 结果 = 归一化记忆系统设置(输入);

    expect(三层(结果).every((值) => Number.isInteger(值) && 值 >= 1)).toBe(true);
    expect(结果.记忆总结API.provider).toBe('');
    expect(typeof 结果.忆庭启用).toBe('boolean');
    expect(typeof 结果.忆庭召回提示词).toBe('string');
  });

  it('未知字段与废弃字段被剥离', () => {
    const 结果 = 归一化记忆系统设置({
      即时转短期阈值: 7,
      短期转中期阈值: 13,
      中期转长期阈值: 29,
      短期转长期阈值: 13,
      未知字段: 'whatever',
    });

    expect(三层(结果)).toEqual([7, 13, 29]);
    expect(结果).not.toHaveProperty('短期转长期阈值');
    expect(结果).not.toHaveProperty('未知字段');
  });

  it('归一化结果一律带契约版本戳', () => {
    expect(归一化记忆系统设置().记忆阈值契约版本).toBe(期望契约版本);
    expect(
      归一化记忆系统设置({ 即时转短期阈值: 7, 短期转中期阈值: 13, 中期转长期阈值: 29 }).记忆阈值契约版本,
    ).toBe(期望契约版本);
  });

  it('提示词回落到旧版默认时，阈值仍走已迁移值', () => {
    const 结果 = 归一化记忆系统设置({
      即时转短期阈值: 25,
      短期转中期阈值: 20,
      中期转长期阈值: 10,
    });

    expect(结果.即时转短期提示词).toBe(当前默认.即时转短期提示词);
    expect(三层(结果)).toEqual(三层(当前默认));
  });
});
