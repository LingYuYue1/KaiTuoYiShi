export const paths: 命途定义[] = Object.values(PATH_CATALOG);

export function getPath(id: string): 命途目录项 | undefined {
  return Object.hasOwn(PATH_CATALOG, id) ? PATH_CATALOG[id as 命途ID] : undefined;
}

export function 获取命途特质(id: 命途ID): 命途特质[] {
  return PATH_CATALOG[id].traits;
}

function catalogField<K extends 'traits' | 'belief'>(field: K): Record<命途ID, 命途目录项[K]> {
  const out = {} as Record<命途ID, 命途目录项[K]>;
  for (const id of Object.keys(PATH_CATALOG) as 命途ID[]) {
    out[id] = PATH_CATALOG[id][field];
  }
  return out;
}

export const PATH_TRAIT_DEFS: Record<命途ID, 命途特质[]> = catalogField('traits');
export const PATH_CORE_BELIEFS: Record<命途ID, 命途核心理念> = catalogField('belief');

const PATH_ALIASES: Record<string, 命途ID> = {};
for (const def of paths) {
  PATH_ALIASES[def.id] = def.id;
  PATH_ALIASES[def.name] = def.id;
}

export function 解析命途ID(raw: string): 命途ID | null {
  const trimmed = raw.trim().replace(/^["']|["']$/g, '');
  if (!trimmed) return null;
  return PATH_ALIASES[trimmed.toLowerCase()] ?? PATH_ALIASES[trimmed] ?? null;
}
